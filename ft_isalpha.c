#include "libft.h"

int	ft_isalpha(char l)
{
	unsigned char l2;

	l2 = (unsigned char)l;
	if ((l2 <= 'z' && l2 >= 'a') || (l2 <= 'Z' && l2 >= 'A'))
		return (1);
	return (0);
}
